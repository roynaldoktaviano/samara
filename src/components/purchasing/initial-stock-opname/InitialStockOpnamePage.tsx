// Both popups reuse the Items & Pricing form (ItemFormFields) so a product created or
// edited here looks and behaves exactly like one made in Items & Pricing. The type/catalog
// list comes from an opname-scoped endpoint — the Purchasing ones 401 for FD/Warehouse.
function useOpnameCatalog() {
  const [typeConfigs, setTypeConfigs] = useState<ItemTypeConfig[]>([])
  const [catalog, setCatalog] = useState<CatalogItem[]>([])
  const [loaded, setLoaded] = useState(false)
  useEffect(() => {
    fetch('/api/purchasing/initial-stock-opname/catalog')
      .then(r => r.ok ? r.json() : { types: [], items: [] })
      .then((d: { types: ItemTypeConfig[]; items: CatalogItem[] }) => { setTypeConfigs(d.types); setCatalog(d.items); setLoaded(true) })
  }, [])
  return { typeConfigs, catalog, loaded }
}

